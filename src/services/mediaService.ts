import { supabase, isSupabaseConfigured, BUCKET_NAME } from '../lib/supabase';
import { MediaItem } from '../types/portfolio';

const LOCAL_STORAGE_KEY_MEDIA = 'dhipash_portfolio_media';

const getLocalMedia = (): MediaItem[] => {
  const cached = localStorage.getItem(LOCAL_STORAGE_KEY_MEDIA);
  if (cached) {
    try {
      return JSON.parse(cached);
    } catch {}
  }
  return [];
};

const saveLocalMedia = (items: MediaItem[]) => {
  localStorage.setItem(LOCAL_STORAGE_KEY_MEDIA, JSON.stringify(items));
};

export interface UploadOptions {
  folder: 'profile' | 'projects' | 'certifications' | 'resume' | 'general';
  maxSizeBytes?: number;
  allowedTypes?: string[];
}

const DEFAULT_ALLOWED_TYPES = ['image/jpeg', 'image/png', 'image/webp', 'application/pdf'];
const DEFAULT_MAX_SIZE = 10 * 1024 * 1024; // 10MB

export const uploadMediaFile = async (
  file: File, 
  options: UploadOptions = { folder: 'general' }
): Promise<MediaItem> => {
  const allowed = options.allowedTypes || DEFAULT_ALLOWED_TYPES;
  const maxSize = options.maxSizeBytes || DEFAULT_MAX_SIZE;

  if (!allowed.includes(file.type)) {
    throw new Error(`Invalid file type: ${file.type}. Allowed: ${allowed.join(', ')}`);
  }

  if (file.size > maxSize) {
    throw new Error(`File is too large (${(file.size / 1024 / 1024).toFixed(1)}MB). Limit is ${(maxSize / 1024 / 1024).toFixed(0)}MB.`);
  }

  const fileExt = file.name.split('.').pop();
  const fileName = `${Date.now()}-${Math.random().toString(36).substring(2, 8)}.${fileExt}`;
  const filePath = `${options.folder}/${fileName}`;

  if (isSupabaseConfigured() && supabase) {
    const { error: uploadError } = await supabase.storage
      .from(BUCKET_NAME)
      .upload(filePath, file, {
        cacheControl: '3600',
        upsert: true,
      });

    if (uploadError) throw uploadError;

    const { data: urlData } = supabase.storage
      .from(BUCKET_NAME)
      .getPublicUrl(filePath);

    const publicUrl = urlData.publicUrl;

    let mediaRecord: MediaItem = {
      id: `m-${Date.now()}`,
      name: file.name,
      file_path: filePath,
      public_url: publicUrl,
      mime_type: file.type,
      size_bytes: file.size,
      folder: options.folder,
      created_at: new Date().toISOString(),
    };

    // Save record to media table with valid UUID generated by Postgres
    try {
      const { data: dbData, error: dbError } = await supabase
        .from('media')
        .insert([{
          name: file.name,
          file_path: filePath,
          public_url: publicUrl,
          mime_type: file.type,
          size_bytes: file.size,
          folder: options.folder,
        }])
        .select()
        .single();

      if (!dbError && dbData) {
        mediaRecord = dbData as MediaItem;
      } else if (dbError) {
        console.warn('Could not record to media table:', dbError.message);
      }
    } catch (err) {
      console.warn('Could not record to media table:', err);
    }

    return mediaRecord;
  }

  // Graceful fallback: convert to base64 Data URL for local preview
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => {
      const publicUrl = reader.result as string;
      const mediaRecord: MediaItem = {
        id: `m-${Date.now()}`,
        name: file.name,
        file_path: filePath,
        public_url: publicUrl,
        mime_type: file.type,
        size_bytes: file.size,
        folder: options.folder,
        created_at: new Date().toISOString(),
      };
      const list = getLocalMedia();
      saveLocalMedia([mediaRecord, ...list]);
      resolve(mediaRecord);
    };
    reader.onerror = () => reject(new Error('Failed to read file'));
    reader.readAsDataURL(file);
  });
};

export const getMediaList = async (folder?: string): Promise<MediaItem[]> => {
  if (isSupabaseConfigured() && supabase) {
    try {
      let query = supabase.from('media').select('*').order('created_at', { ascending: false });
      if (folder) {
        query = query.eq('folder', folder);
      }
      const { data, error } = await query;
      if (!error && data) return data as MediaItem[];
    } catch (err) {
      console.warn('Error fetching media records from Supabase:', err);
    }
  }

  const list = getLocalMedia();
  return folder ? list.filter(m => m.folder === folder) : list;
};

export const deleteMediaFile = async (item: MediaItem): Promise<void> => {
  if (isSupabaseConfigured() && supabase) {
    try {
      await supabase.storage.from(BUCKET_NAME).remove([item.file_path]);
      await supabase.from('media').delete().eq('id', item.id);
      return;
    } catch (err) {
      console.warn('Error deleting from Supabase storage:', err);
    }
  }

  const list = getLocalMedia();
  saveLocalMedia(list.filter(m => m.id !== item.id));
};
